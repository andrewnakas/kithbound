def _slots(variant):
    out = np.zeros((48, 32), np.uint8)
    for i, k in enumerate(ORDER):
        s = T(SYMBOLS[k], 16, 16)
        if variant == "blue":                   # the DUSK cabinet: light and grey fills swap
            s = np.where(s == 1, 2, np.where(s == 2, 1, s)).astype(np.uint8)
        s = np.roll(s, 1, axis=0)
        out[i * 8:i * 8 + 8, 0:16] = s[0:8]
        out[i * 8:i * 8 + 8, 16:32] = s[8:16]
    return out


