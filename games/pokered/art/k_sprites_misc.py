"""KITHBOUND small pictures: fishing poses, dust puff, party icons, trade bits, slot
symbols, falling star, trainer-card badges + leader faces, hop shadow, map cursor.
All our own designs ('.' 0, '-' 1, '+' 2, '#' 3)."""
import numpy as np

from games.pokered.art import drawer
from games.pokered.art import k_sprites_lib as L

CH = {".": 0, " ": 0, "-": 1, "+": 2, "#": 3}


def T(rows, w=None, h=None):
    h = h or len(rows)
    w = w or max(len(r) for r in rows)
    a = np.zeros((h, w), np.uint8)
    for y, r in enumerate(rows[:h]):
        for x, c in enumerate(r[:w]):
            a[y, x] = CH[c]
    return a


def overlay(a, rows, x0, y0):
    for j, r in enumerate(rows):
        for i, c in enumerate(r):
            if c != " " and 0 <= y0 + j < a.shape[0] and 0 <= x0 + i < a.shape[1]:
                a[y0 + j, x0 + i] = CH[c]
    return a


