@drawer("overworld/shadow.png")
def k_shadow(rel, a):
    """Top-left quarter of the hop shadow: a dotted lozenge with a clear ring (mirrored)."""
    q = np.zeros((8, 8), np.uint8)
    for y in range(8):
        for x in range(8):
            d = (7 - x) * 0.55 + (7 - y) * 1.35
            if d <= 7.2 and ((x + y) % 2 == 0 or d >= 6.0):
                q[y, x] = 3
            if 4.2 <= d <= 5.0:
                q[y, x] = 0
    return q


