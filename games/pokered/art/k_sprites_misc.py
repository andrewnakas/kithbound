def _gb_draw():
    """Portrait handheld, 48x64 (6x8 tiles). Features sit in the tiles the build keeps
    unique; shared tiles (spec classes) stay plain edge or plain body."""
    from games.pokered.art.tilekit import C
    c = C(48, 64)
    c.frame(0, 0, 48, 64, 3, fill=1)
    for x, y in ((0, 0), (47, 0), (0, 63), (47, 63)):
        c.px(x, y, 0)
    c.frame(8, 9, 40, 31, 3, fill=2)                       # screen bezel
    c.frame(11, 12, 37, 28, 3, fill=0)                     # screen
    c.px(9, 10, 1); c.px(38, 29, 3)
    c.ellipse(38.5, 10.5, 1.2, 1.2, 1, outline=3)          # power lamp in the bezel corner
    c.rect(8, 42, 16, 46, 3); c.rect(10, 40, 14, 48, 3)     # plus pad
    c.rect(9, 43, 15, 45, 2); c.rect(11, 41, 13, 47, 2)
    c.px(11, 43, 3); c.px(12, 44, 3)
    for cx, cy in ((35, 44), (42, 38)):                    # two round keys
        c.ellipse(cx, cy, 3.2, 3.2, 2, outline=3)
        c.px(int(cx) - 1, int(cy) - 1, 1)
    c.rect(18, 51, 23, 53, 3); c.rect(26, 51, 31, 53, 3)    # two pill switches
    for x in range(34, 46, 3):                             # speaker slots
        c.line(x, 59, x + 3, 50, 2)
    c.vline(1, 41, 45, 2)                                  # side catch on the left edge
    c.px(2, 26, 2)
    return c.a


@drawer("trade/game_boy.png")
def k_game_boy(rel, a):
    """Our handheld: wide body, slotted speaker, square screen, plus pad, three keys.
    The build shares some tiles (spec classes); each shared class gets its plainest
    member's tile so the forced copies fall on plain body."""
    img = _gb_draw()
    cls = a.get("classes")
    if cls:
        tiles = [img[(i // 6) * 8:(i // 6) * 8 + 8, (i % 6) * 8:(i % 6) * 8 + 8].copy() for i in range(48)]
        groups = {}
        for i, k in enumerate(cls):
            groups.setdefault(k, []).append(i)
        for k, mem in groups.items():
            if len(mem) > 1:
                best = min(mem, key=lambda i: (np.count_nonzero(tiles[i] != np.bincount(tiles[i].ravel()).argmax()), i))
                for i in mem:
                    tiles[i] = tiles[best].copy()
        for i, t in enumerate(tiles):
            img[(i // 6) * 8:(i // 6) * 8 + 8, (i % 6) * 8:(i % 6) * 8 + 8] = t
    return img


