"""KITHBOUND overworld creatures and objects, hand-drawn text art (16x16 frames).
'.' transparent, '-' light, '+' grey, '#' black. Our own designs."""
import numpy as np

CH = {".": 0, " ": 0, "-": 1, "+": 2, "#": 3}


def T(rows):
    a = np.zeros((16, 16), np.uint8)
    for y, r in enumerate(rows[:16]):
        for x, c in enumerate(r[:16]):
            a[y, x] = CH[c]
    return a


def hop(a, dy=-1):
    out = np.zeros_like(a)
    if dy < 0:
        out[:dy] = a[-dy:]
    else:
        out[dy:] = a[:16 - dy]
    return out


